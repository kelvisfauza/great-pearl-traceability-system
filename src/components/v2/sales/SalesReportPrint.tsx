import { useState } from "react";
import { supabase } from "@/integrations/supabase/client";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Printer, Loader2 } from "lucide-react";
import { format, subDays } from "date-fns";
import { useToast } from "@/hooks/use-toast";
import {
  COMPANY_NAME,
  COMPANY_TAGLINE,
  COMPANY_ADDRESS,
  COMPANY_PHONES,
  COMPANY_EMAIL,
  COMPANY_WEBSITE,
  LOGO_URL,
} from "@/utils/companyBrand";

interface SaleRow {
  id: string;
  customer: string;
  coffee_type: string;
  weight: number;
  unit_price: number;
  total_amount: number;
  status: string;
  date: string;
  created_at: string;
}

const SalesReportPrint = () => {
  const [from, setFrom] = useState(format(subDays(new Date(), 30), "yyyy-MM-dd"));
  const [to, setTo] = useState(format(new Date(), "yyyy-MM-dd"));
  const [busy, setBusy] = useState(false);
  const { toast } = useToast();

  const handlePrint = async () => {
    setBusy(true);
    try {
      const { data, error } = await supabase
        .from("sales_transactions")
        .select("*")
        .gte("date", from)
        .lte("date", to)
        .order("date", { ascending: true });

      if (error) throw error;
      const rows = (data || []) as SaleRow[];
      if (rows.length === 0) {
        toast({ title: "Nothing to print", description: "No sales in that date range." });
        return;
      }

      const totalWeight = rows.reduce((s, r) => s + (Number(r.weight) || 0), 0);
      const totalAmount = rows.reduce((s, r) => s + (Number(r.total_amount) || 0), 0);

      const bodyRows = rows
        .map(
          (r, i) => `<tr>
            <td>${i + 1}</td>
            <td>${format(new Date(r.date || r.created_at), "dd MMM yyyy")}</td>
            <td>${escapeHtml(r.customer)}</td>
            <td>${escapeHtml(r.coffee_type)}</td>
            <td class="num">${Number(r.weight || 0).toLocaleString()}</td>
            <td class="num">${Number(r.unit_price || 0).toLocaleString()}</td>
            <td class="num">${Number(r.total_amount || 0).toLocaleString()}</td>
            <td>${escapeHtml(r.status || "")}</td>
          </tr>`
        )
        .join("");

      const html = `<!doctype html><html><head><meta charset="utf-8"><title>Sales Report ${from} to ${to}</title>
        <style>
          body { font-family: Arial, sans-serif; margin: 24px; color: #111; }
          .header { display: flex; align-items: center; gap: 16px; border-bottom: 3px solid #14532d; padding-bottom: 12px; }
          .header img { height: 64px; }
          .header h1 { margin: 0; font-size: 22px; color: #14532d; }
          .header .tag { margin: 2px 0; font-size: 12px; color: #555; }
          .header .meta { font-size: 11px; color: #555; }
          h2 { margin: 18px 0 4px; font-size: 16px; }
          .range { font-size: 12px; color: #555; margin-bottom: 12px; }
          table { width: 100%; border-collapse: collapse; font-size: 12px; }
          th, td { border: 1px solid #ccc; padding: 6px 8px; text-align: left; }
          th { background: #14532d; color: #fff; }
          .num { text-align: right; }
          tfoot td { font-weight: bold; background: #f0fdf4; }
          .footer { margin-top: 24px; font-size: 11px; color: #555; display: flex; justify-content: space-between; }
          @media print { body { margin: 10mm; } }
        </style></head><body>
        <div class="header">
          <img src="${window.location.origin}${LOGO_URL}" alt="logo" />
          <div>
            <h1>${COMPANY_NAME}</h1>
            <p class="tag">${COMPANY_TAGLINE}</p>
            <p class="meta">${COMPANY_ADDRESS} · Tel: ${COMPANY_PHONES}</p>
            <p class="meta">${COMPANY_EMAIL} · ${COMPANY_WEBSITE}</p>
          </div>
        </div>
        <h2>Sales Report</h2>
        <p class="range">Period: ${format(new Date(from), "dd MMM yyyy")} – ${format(new Date(to), "dd MMM yyyy")} · ${rows.length} sale(s) · Printed ${format(new Date(), "dd MMM yyyy HH:mm")}</p>
        <table>
          <thead><tr>
            <th>#</th><th>Date</th><th>Customer</th><th>Coffee Type</th>
            <th class="num">Weight (kg)</th><th class="num">Unit Price (UGX)</th><th class="num">Total (UGX)</th><th>Status</th>
          </tr></thead>
          <tbody>${bodyRows}</tbody>
          <tfoot><tr>
            <td colspan="4">TOTALS</td>
            <td class="num">${totalWeight.toLocaleString()}</td>
            <td></td>
            <td class="num">${totalAmount.toLocaleString()}</td>
            <td></td>
          </tr></tfoot>
        </table>
        <div class="footer">
          <span>Generated by ${COMPANY_NAME} sales system</span>
          <span>Signature: ______________________</span>
        </div>
        <script>window.onload = function(){ window.print(); }</script>
        </body></html>`;

      const win = window.open("", "_blank");
      if (!win) {
        toast({ title: "Pop-up blocked", description: "Allow pop-ups to print the report.", variant: "destructive" });
        return;
      }
      win.document.write(html);
      win.document.close();
    } catch (e) {
      console.error("Sales report print failed:", e);
      toast({ title: "Could not print", description: "Failed to load the sales report.", variant: "destructive" });
    } finally {
      setBusy(false);
    }
  };

  return (
    <div className="flex flex-wrap items-end gap-3">
      <div className="space-y-1">
        <Label htmlFor="sales-report-from" className="text-xs">From</Label>
        <Input id="sales-report-from" type="date" value={from} onChange={(e) => setFrom(e.target.value)} className="w-40" />
      </div>
      <div className="space-y-1">
        <Label htmlFor="sales-report-to" className="text-xs">To</Label>
        <Input id="sales-report-to" type="date" value={to} onChange={(e) => setTo(e.target.value)} className="w-40" />
      </div>
      <Button onClick={handlePrint} disabled={busy} variant="outline">
        {busy ? <Loader2 className="h-4 w-4 animate-spin mr-2" /> : <Printer className="h-4 w-4 mr-2" />}
        Print sales report
      </Button>
    </div>
  );
};

const escapeHtml = (s: string) =>
  String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

export default SalesReportPrint;
